/* URL slug for each tip's detail page (tips/<slug>.html).
   Used by script.js (cards) and build-tips.js (generator) — keep identical. */
function tipSlug(title) {
  return String(title)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

